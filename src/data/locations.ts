export function searchLocations(query: string): LocationItem[] {
  const trimmed = query.trim().toLowerCase();
  if (!trimmed) return TAMIL_LOCATIONS.slice(0, 10);
  return TAMIL_LOCATIONS.filter(
    (loc) =>
      loc.tamil.includes(trimmed) ||
      loc.english.toLowerCase().includes(trimmed) ||
      (loc.district && loc.district.includes(trimmed))
  ).slice(0, 15);
}
